package com.calypsan.listenup.gradle

import org.gradle.api.DefaultTask
import org.gradle.api.Project
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import org.gradle.api.tasks.TaskProvider
import java.io.File

/**
 * Single-source helpers for reading the repo-root `VERSION` file and emitting generated
 * `*Version.kt` constants for the client and server modules.
 */
object ListenUpVersion {
    const val DEFAULT_VERSION: String = "0.0.1"

    fun parseVersionText(raw: String?): String =
        raw
            ?.trim()
            ?.removePrefix("v")
            ?.ifEmpty { DEFAULT_VERSION }
            ?: DEFAULT_VERSION

    fun readVersionFile(versionFile: File): String = parseVersionText(versionFile.takeIf { it.exists() }?.readText())

    fun renderVersionFile(
        packageName: String,
        constantName: String,
        generatedBy: String,
        version: String,
    ): String =
        buildString {
            appendLine("package $packageName")
            appendLine()
            appendLine("// AUTO-GENERATED by $generatedBy — do not edit.")
            appendLine("internal const val $constantName: String = \"$version\"")
        }
}

/**
 * Generates a Kotlin file holding an internal `const val` read from the repo-root `VERSION` file.
 */
@CacheableTask
abstract class GenerateVersionConstantTask : DefaultTask() {
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val versionFile: RegularFileProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val fileName: Property<String>

    @get:Input
    abstract val constantName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val version =
            versionFile.orNull
                ?.asFile
                ?.let(ListenUpVersion::readVersionFile)
                ?: ListenUpVersion.DEFAULT_VERSION
        val outFile =
            outputDir
                .get()
                .file("${pkg.replace('.', '/')}/${fileName.get()}")
                .asFile
        outFile.parentFile.mkdirs()
        outFile.writeText(
            ListenUpVersion.renderVersionFile(
                packageName = pkg,
                constantName = constantName.get(),
                generatedBy = name,
                version = version,
            ),
        )
    }
}

/**
 * Registers a cacheable [GenerateVersionConstantTask] reading the repo-root `VERSION` file into
 * `build/generated/version/kotlin`.
 */
fun Project.registerVersionConstantTask(
    taskName: String,
    packageName: String,
    fileName: String,
    constantName: String,
): TaskProvider<GenerateVersionConstantTask> {
    val rootVersionFile = rootProject.layout.projectDirectory.file("VERSION")
    val generatedDir = layout.buildDirectory.dir("generated/version/kotlin")
    return tasks.register(taskName, GenerateVersionConstantTask::class.java) {
        group = "build"
        description = "Embeds the repo-root VERSION file into a generated $fileName"
        versionFile.set(rootVersionFile)
        this.packageName.set(packageName)
        this.fileName.set(fileName)
        this.constantName.set(constantName)
        outputDir.set(generatedDir)
    }
}
