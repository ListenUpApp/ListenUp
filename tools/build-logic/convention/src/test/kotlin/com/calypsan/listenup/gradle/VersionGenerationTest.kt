package com.calypsan.listenup.gradle

import java.nio.file.Files
import kotlin.test.Test
import kotlin.test.assertEquals

class VersionGenerationTest {
    @Test
    fun `parseVersionText trims whitespace, strips leading v, and falls back on blank inputs`() {
        assertEquals("1.2.3", ListenUpVersion.parseVersionText("1.2.3"))
        assertEquals("1.2.3", ListenUpVersion.parseVersionText("  v1.2.3\n"))
        assertEquals("2.0.0-rc1", ListenUpVersion.parseVersionText("v2.0.0-rc1"))
        assertEquals(ListenUpVersion.DEFAULT_VERSION, ListenUpVersion.parseVersionText(""))
        assertEquals(ListenUpVersion.DEFAULT_VERSION, ListenUpVersion.parseVersionText("  v \n"))
        assertEquals(ListenUpVersion.DEFAULT_VERSION, ListenUpVersion.parseVersionText(null))
    }

    @Test
    fun `readVersionFile reads existing files and falls back when absent`() {
        val tempDir = Files.createTempDirectory("listenup-version-test").toFile()
        try {
            val missing = tempDir.resolve("VERSION")
            assertEquals(ListenUpVersion.DEFAULT_VERSION, ListenUpVersion.readVersionFile(missing))

            missing.writeText("v3.4.5\n")
            assertEquals("3.4.5", ListenUpVersion.readVersionFile(missing))
        } finally {
            tempDir.deleteRecursively()
        }
    }

    @Test
    fun `renderVersionFile emits expected Kotlin constant declaration`() {
        val rendered =
            ListenUpVersion.renderVersionFile(
                packageName = "com.calypsan.listenup.server.api",
                constantName = "SERVER_VERSION",
                generatedBy = "generateServerVersion",
                version = "1.4.0",
            )
        val expected =
            """
            package com.calypsan.listenup.server.api

            // AUTO-GENERATED by generateServerVersion — do not edit.
            internal const val SERVER_VERSION: String = "1.4.0"

            """.trimIndent()
        assertEquals(expected, rendered)
    }
}
